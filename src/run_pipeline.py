from __future__ import annotations

import argparse
import json
from datetime import datetime
import os
import subprocess
import time
from pathlib import Path
import sys
from typing import Any, Dict, Sequence

try:
    from .check_data import check_raw_data
    from .coco_validation import validate_coco_file
    from .config_utils import DEFAULT_CONFIG_PATH, PROJECT_ROOT, get_required_path, load_config
    from .prepare_rfdetr_dataset import prepare_dataset
except ImportError:  # pragma: no cover
    from check_data import check_raw_data
    from coco_validation import validate_coco_file
    from config_utils import DEFAULT_CONFIG_PATH, PROJECT_ROOT, get_required_path, load_config
    from prepare_rfdetr_dataset import prepare_dataset


def log(message: str) -> None:
    print(message)


def validate_coco_dataset(processed_root: Path) -> Dict[str, Any]:
    report: Dict[str, Any] = {
        "status": "success",
        "processed_root": str(processed_root),
        "splits": {},
    }

    for split in ["train", "valid"]:
        ann_path = processed_root / split / "_annotations.coco.json"
        img_dir = processed_root / split

        report["splits"][split] = validate_coco_file(ann_path, img_dir)

    return report


def write_pipeline_report(report: Dict[str, Any], experiments_root: Path) -> Path:
    experiments_root.mkdir(parents=True, exist_ok=True)
    report_path = experiments_root / "pipeline_report.json"
    with report_path.open("w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    return report_path


def run_subprocess(script_path: Path, arguments: Sequence[str] = ()) -> subprocess.CompletedProcess:
    # RF-DETR delegates COCO JSON loading to pycocotools. On Windows,
    # pycocotools uses the process default encoding, which can otherwise be
    # GBK and fail on the UTF-8 annotation files generated by this project.
    env = os.environ.copy()
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    return subprocess.run(
        [sys.executable, str(script_path), *arguments],
        cwd=str(PROJECT_ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
    )


def build_artifacts(experiment_dir: Path | None) -> Dict[str, str]:
    if experiment_dir is None:
        return {"experiment_dir": "", "checkpoint": "", "logs": ""}

    checkpoint_dir = experiment_dir / "checkpoints"
    logs_dir = experiment_dir / "logs"

    checkpoint = ""
    if checkpoint_dir.exists():
        best = checkpoint_dir / "checkpoint_best_total.pth"
        if best.is_file():
            checkpoint = str(best)

    return {
        "experiment_dir": str(experiment_dir),
        "checkpoint": checkpoint,
        "logs": str(logs_dir),
        "training_report": str(experiment_dir / "results" / "training_report.md"),
        "epoch_metrics": str(experiment_dir / "results" / "epoch_metrics.csv"),
    }


def load_evaluation_report(experiment_dir: Path | None) -> Dict[str, Any]:
    if experiment_dir is None:
        return {"status": "failed", "error": "evaluation report not found"}

    report_path = experiment_dir / "results" / "evaluation_report.json"
    if not report_path.exists():
        return {"status": "failed", "error": "evaluation report not found"}

    with report_path.open("r", encoding="utf-8") as f:
        report = json.load(f)

    return {
        "status": "success",
        "report_path": str(report_path),
        "metrics": report.get("metrics", {}),
    }


def run_stage(stage_name: str, stage_func):
    log(stage_name)
    return stage_func()


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Run the RF-DETR pollen pipeline.")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG_PATH)
    parser.add_argument("--experiment-name", default=None)
    parser.add_argument("--overwrite", action="store_true", help="Replace processed data after validation.")
    parser.add_argument("--prepare-only", action="store_true", help="Stop after data preparation and validation.")
    parser.add_argument("--reuse-prepared", action="store_true", help="Validate/reuse fixed processed data without re-splitting.")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    config_path = args.config.expanduser().resolve()
    experiments_root = PROJECT_ROOT / "experiments"
    pipeline_report: Dict[str, Any] = {
        "status": "running",
        "timestamp": datetime.now().isoformat(),
        "config": str(config_path),
        "stages": {},
        "artifacts": {"experiment_dir": "", "checkpoint": "", "logs": ""},
    }
    pipeline_started = time.perf_counter()

    print("[PIPELINE] Starting pipeline")

    try:
        config = load_config(config_path)
        raw_root = get_required_path(config, "raw_data", "root", PROJECT_ROOT)
        processed_root = get_required_path(config, "processed_data", "root", PROJECT_ROOT)
        dataset_root = get_required_path(config, "dataset", "path", PROJECT_ROOT)
        experiments_root = get_required_path(config, "experiment", "root", PROJECT_ROOT)

        if dataset_root != processed_root:
            raise ValueError(
                "Config paths processed_data.root and dataset.path must resolve "
                "to the same directory"
            )
        if not raw_root.exists():
            raise FileNotFoundError(f"Configured raw dataset path does not exist: {raw_root}")

        processed_root.parent.mkdir(parents=True, exist_ok=True)

        model_name = str(config.get("model", {}).get("name", "experiment"))
        experiment_name = args.experiment_name or f"{model_name}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
        if Path(experiment_name).name != experiment_name:
            raise ValueError("Experiment name must not contain path separators")
        experiment_dir = experiments_root / experiment_name
        pipeline_report["experiment_name"] = experiment_name

        stage_started = time.perf_counter()
        print("[1/5] Raw data check")
        raw_report = check_raw_data(raw_root)
        if raw_report.get("status") != "passed":
            raise RuntimeError("raw data check reported a failure")
        pipeline_report["stages"]["raw_check"] = {"status": "passed", "report": raw_report,
                                                     "duration_seconds": time.perf_counter() - stage_started}
        print("PASS")

        stage_started = time.perf_counter()
        print("[2/5] Dataset preparation")
        prep_report = {"status": "reused", "path": str(processed_root)} if args.reuse_prepared else prepare_dataset(
            raw_base=raw_root,
            output_root=processed_root,
            train_ratio=float(config.get("data_split", {}).get("train_ratio", 0.8)),
            seed=int(config.get("project", {}).get("seed", 42)),
            overwrite=args.overwrite,
        )
        pipeline_report["stages"]["dataset_prepare"] = {"status": "passed", "report": prep_report,
                                                          "duration_seconds": time.perf_counter() - stage_started}
        print("PASS")

        stage_started = time.perf_counter()
        print("[3/5] COCO validation")
        coco_report = validate_coco_dataset(processed_root)
        pipeline_report["stages"]["validation"] = {"status": "passed", "report": coco_report,
                                                      "duration_seconds": time.perf_counter() - stage_started}
        print("PASS")

        if args.prepare_only:
            pipeline_report["stages"]["training"] = {"status": "skipped"}
            pipeline_report["stages"]["evaluation"] = {"status": "skipped"}
        else:
            stage_started = time.perf_counter()
            print("[4/5] Training")
            train_script = PROJECT_ROOT / "src" / "train_rfdetr.py"
            train_result = run_subprocess(
                train_script,
                ["--config", str(config_path), "--experiment-name", experiment_name],
            )
            training_stage: Dict[str, Any] = {
                "status": "passed" if train_result.returncode == 0 else "failed",
                "returncode": train_result.returncode,
                "stdout": train_result.stdout,
                "stderr": train_result.stderr,
                "duration_seconds": time.perf_counter() - stage_started,
            }
            pipeline_report["stages"]["training"] = training_stage
            if train_result.returncode != 0:
                raise RuntimeError("training stage failed")
            print(train_result.stdout)

            pipeline_report["artifacts"] = build_artifacts(experiment_dir)

            print("[5/5] Evaluation")
        if not args.prepare_only:
            stage_started = time.perf_counter()
            evaluation_stage: Dict[str, Any] = {
                "status": "passed",
                "source": "automatic post-training evaluation",
                "duration_seconds": time.perf_counter() - stage_started,
            }
            evaluation_report = load_evaluation_report(experiment_dir)
            evaluation_stage["report_load_status"] = evaluation_report.get("status", "failed")
            if evaluation_report.get("status") == "success":
                evaluation_stage["report_path"] = evaluation_report.get("report_path", "")
                evaluation_stage["metrics"] = evaluation_report.get("metrics", {})
            else:
                evaluation_stage["error"] = evaluation_report.get("error", "evaluation report not found")
            pipeline_report["stages"]["evaluation"] = evaluation_stage
            if evaluation_report.get("status") != "success":
                raise RuntimeError("evaluation completed without a readable evaluation report")

        pipeline_report["status"] = "success"
    except Exception as exc:
        print("[PIPELINE] Stage failed: pipeline execution")
        print("Error:")
        print(exc)
        print("Pipeline stopped.")
        pipeline_report["status"] = "failed"
        pipeline_report["error"] = str(exc)

    pipeline_report["duration_seconds"] = time.perf_counter() - pipeline_started
    report_path = write_pipeline_report(pipeline_report, experiments_root)
    print(f"Pipeline report saved to: {report_path}")
    return 0 if pipeline_report["status"] == "success" else 1


if __name__ == "__main__":
    sys.exit(main())